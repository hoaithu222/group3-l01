#!/usr/bin/env node
/**
 * ============================================================================
 * sync:contracts — p0-09 (app)
 * ============================================================================
 * Đọc `../contracts/{socket-events,push-types,error-codes}.json` (gốc repo,
 * BE ghi — xem `contracts/README.md`) → ghi `src/core/contracts/*.generated.ts`
 * (COMMIT). Node THUẦN (fs/crypto/path — không thêm devDependency mới, giữ
 * `npm ci` gọn, xem `docs/plans/phase-0-common/p0-09-contract-tooling/app.md` §4.1).
 *
 * Mỗi file sinh có header `// source-sha256: <hash>` — test tươi (chưa viết ở
 * đợt này) so hash này với `sha256(contracts/*.json)` hiện tại để biết
 * "generated" có bị stale hay không (CTR-04/CTR-07).
 *
 * ⚠ `socket-events.json`/`push-types.json` hiện tại là JSON CHÉP TAY (payload
 * mô tả bằng text, không phải JSON Schema thật — xem field "note" trong từng
 * file) — vì vậy `SocketPayloads`/dữ liệu payload sinh ra ở đây là `unknown`
 * (an toàn, không suy đoán sai hình dạng) thay vì kiểu object chi tiết. Khi
 * BE chuyển sang catalog Zod thật (README §9 việc #4), script này cần sửa lại
 * phần đọc JSON Schema → TS type.
 *
 * Sử dụng: npm run sync:contracts
 * ============================================================================
 */
import { readFileSync, writeFileSync, mkdirSync } from "node:fs";
import { createHash } from "node:crypto";
import path from "node:path";
import { fileURLToPath } from "node:url";

const __dirname = path.dirname(fileURLToPath(import.meta.url));
const CONTRACTS_DIR = path.resolve(__dirname, "../../contracts");
const OUT_DIR = path.resolve(__dirname, "../src/core/contracts");

function readJson(name) {
  const p = path.join(CONTRACTS_DIR, name);
  const raw = readFileSync(p, "utf8");
  return { raw, data: JSON.parse(raw) };
}

function sha256(text) {
  return createHash("sha256").update(text).digest("hex");
}

/** `"message:created"` / `"call.answered-elsewhere"` → `MESSAGE_CREATED` / `CALL_ANSWERED_ELSEWHERE`. */
function toConstKey(name) {
  return name.replace(/[^a-zA-Z0-9]+/g, "_").toUpperCase();
}

function header(sourceFile, sourceHash) {
  return [
    "// AUTO-GENERATED by app/scripts/sync-contracts.mjs — KHÔNG SỬA TAY.",
    `// source: contracts/${sourceFile}`,
    `// source-sha256: ${sourceHash}`,
    "",
  ].join("\n");
}

function writeGenerated(fileName, content) {
  mkdirSync(OUT_DIR, { recursive: true });
  writeFileSync(path.join(OUT_DIR, fileName), content, "utf8");
}

function buildSocketEvents() {
  const { raw, data } = readJson("socket-events.json");
  const hash = sha256(raw);
  const events = [...data.events].sort((a, b) => a.name.localeCompare(b.name));

  const constLines = events.map((e) => `  ${toConstKey(e.name)}: "${e.name}",`);
  const payloadLines = events.map((e) => {
    const note = e.payload ? ` /** ${e.payload.replace(/\*\//g, "*\\/")} */` : "";
    return `  "${e.name}": unknown;${note}`;
  });

  const body = `${header("socket-events.json", hash)}
/** Mọi tên sự kiện Socket.IO thật (server + client) — xem \`contracts/socket-events.json\`. */
export const SOCKET_EVENTS = {
${constLines.join("\n")}
} as const;

export type SocketEventName = (typeof SOCKET_EVENTS)[keyof typeof SOCKET_EVENTS];

/**
 * Payload theo tên sự kiện — hiện tại \`unknown\` (xem ghi chú đầu file): JSON
 * nguồn mô tả payload bằng TEXT (\`payload: string\`), chưa phải JSON Schema
 * thật, nên KHÔNG suy ra được field. Dùng \`z.unknown()\`/ép kiểu thủ công tại
 * nơi tiêu thụ cho tới khi BE chuyển sang catalog Zod thật.
 */
export interface SocketPayloads {
${payloadLines.join("\n")}
}
`;
  writeGenerated("socket-events.generated.ts", body);
  return events.length;
}

function buildPushTypes() {
  const { raw, data } = readJson("push-types.json");
  const hash = sha256(raw);
  const types = [...data.types].sort((a, b) => a.type.localeCompare(b.type));

  const constLines = types.map((t) => `  ${toConstKey(t.type)}: "${t.type}",`);
  const channelLines = types.map((t) => `  "${t.type}": "${t.channel}",`);
  const visibleLines = types.map((t) => `  "${t.type}": ${t.visible},`);
  const voipLines = types.map((t) => `  "${t.type}": ${t.voip},`);

  const body = `${header("push-types.json", hash)}
/** Mọi loại push FCM/VoIP canonical — xem \`contracts/push-types.json\`. */
export const PUSH_TYPES = {
${constLines.join("\n")}
} as const;

export type PushType = (typeof PUSH_TYPES)[keyof typeof PUSH_TYPES];

/** Kênh Android (\`default\`|\`mentions\`|\`calls\`) theo loại push. */
export const PUSH_CHANNEL: Record<PushType, "default" | "mentions" | "calls"> = {
${channelLines.join("\n")}
};

/** \`false\` = data-only (không hiển thị notification hệ điều hành), \`true\` = có title/body. */
export const PUSH_VISIBLE: Record<PushType, boolean> = {
${visibleLines.join("\n")}
};

/** \`true\` = gửi qua kênh APNs VoIP riêng (\`VoipPayload\`), không qua FCM thường. */
export const PUSH_VOIP: Record<PushType, boolean> = {
${voipLines.join("\n")}
};
`;
  writeGenerated("push-types.generated.ts", body);
  return types.length;
}

function buildErrorCodes() {
  const { raw, data } = readJson("error-codes.json");
  const hash = sha256(raw);
  const codes = [...data.codes].sort((a, b) => a.code.localeCompare(b.code));

  const lines = codes.map((c) => {
    const httpField = c.http !== undefined ? `, http: ${c.http}` : "";
    const message = c.message.replace(/\\/g, "\\\\").replace(/"/g, '\\"');
    return `  ${c.code}: { message: "${message}"${httpField} },`;
  });

  const body = `${header("error-codes.json", hash)}
/** Mọi mã lỗi nghiệp vụ/hệ thống + thông điệp tiếng Việt (+ HTTP status khi dò được) — xem \`contracts/error-codes.json\`. */
export const ERROR_CODES = {
${lines.join("\n")}
} as const;

export type ErrorCodeName = keyof typeof ERROR_CODES;
`;
  writeGenerated("error-codes.generated.ts", body);
  return codes.length;
}

function buildIndex() {
  const body = `// AUTO-GENERATED by app/scripts/sync-contracts.mjs — KHÔNG SỬA TAY.
export * from "./socket-events.generated";
export * from "./push-types.generated";
export * from "./error-codes.generated";
`;
  writeGenerated("index.ts", body);
}

function main() {
  const eventCount = buildSocketEvents();
  const pushCount = buildPushTypes();
  const codeCount = buildErrorCodes();
  buildIndex();
  console.log(
    `[sync-contracts] Đã ghi ${OUT_DIR} — ${eventCount} socket event, ${pushCount} loại push, ${codeCount} mã lỗi.`
  );
}

main();
